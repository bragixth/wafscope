async def tls_info(t, timeout):
    if t.scheme != "https":
        return {}
    writer = None
    try:
        reader, writer = await asyncio.wait_for(
            asyncio.open_connection(t.host, t.port, ssl=make_ctx(False), server_hostname=t.host), timeout)
        der = writer.get_extra_info("ssl_object").getpeercert(binary_form=True)
        out = {}
        try:
            from cryptography import x509
            cert = x509.load_der_x509_certificate(der)
            out["issuer"] = cert.issuer.rfc4514_string()
            out["subject"] = cert.subject.rfc4514_string()
            try:
                ext = cert.extensions.get_extension_for_class(x509.SubjectAlternativeName)
                out["san"] = ext.value.get_values_for_type(x509.DNSName)[:30]
            except Exception:
                out["san"] = []
        except ImportError:
            out["note"] = "install 'cryptography' to analyse the certificate"
        return out
    except Exception as e:
        return {"error": str(e)}
    finally:
        if writer is not None:
            try:
                writer.close()
            except Exception:
                pass


def _resolvers():
    try:
        with open("/etc/resolv.conf") as f:
            for line in f:
                if line.startswith("nameserver"):
                    ip = line.split()[1]
                    if ":" not in ip:
                        return [ip, "1.1.1.1"]
    except OSError:
        pass
    return ["1.1.1.1", "8.8.8.8"]


def _dns_cname(name, servers, timeout=2.5):
    q = os.urandom(2) + struct.pack(">HHHHH", 0x0100, 1, 0, 0, 0)
    for label in name.rstrip(".").split("."):
        q += bytes([len(label)]) + label.encode("idna")
    q += b"\x00" + struct.pack(">HH", 5, 1)
    data = None
    for srv in servers:
        s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        s.settimeout(timeout)
        try:
            s.sendto(q, (srv, 53))
            data, _ = s.recvfrom(4096)
            break
        except OSError:
            continue
        finally:
            s.close()
    if not data or len(data) < 12:
        return []

    def read_name(p):
        labels, end, hops = [], None, 0
        while True:
            l = data[p]
            if l == 0:
                p += 1
                break
            if l & 0xC0 == 0xC0:
                if end is None:
                    end = p + 2
                p = ((l & 0x3F) << 8) | data[p + 1]
                hops += 1
                if hops > 20:
                    break
                continue
            labels.append(data[p + 1:p + 1 + l].decode("ascii", "replace"))
            p += l + 1
        return ".".join(labels), (end if end is not None else p)

    qd, an = struct.unpack(">HH", data[4:8])
    pos = 12
    for _ in range(qd):
        _, pos = read_name(pos)
        pos += 4
    out = []
    for _ in range(an):
        _, pos = read_name(pos)
        rtype, _c, _ttl, rdlen = struct.unpack(">HHIH", data[pos:pos + 10])
        pos += 10
        if rtype == 5:
            out.append(read_name(pos)[0])
        pos += rdlen
    return out


def dns_info(host):
    info = {"ips": [], "cnames": []}
    try:
        ipaddress.ip_address(host)
        info["ips"] = [host]
        return info
    except ValueError:
        pass
    try:
        info["ips"] = sorted({ai[4][0] for ai in socket.getaddrinfo(host, None, proto=socket.IPPROTO_TCP)})
    except OSError:
        pass
    servers, name = _resolvers(), host
    for _ in range(6):
        try:
            cn = _dns_cname(name, servers)
        except Exception:
            break
        if not cn:
            break
        info["cnames"].append(cn[0])
        name = cn[0]
    return info


