@dataclass
class Target:
    scheme: str
    host: str
    port: int
    hostheader: str


@dataclass
class Resp:
    status: int = 0
    reason: str = ""
    headers: list = field(default_factory=list)
    body: bytes = b""
    elapsed: float = 0.0
    error: str = ""
    _text: str = None

    def h(self, name):
        return [v for k, v in self.headers if k == name]

    @property
    def text(self):
        if self._text is None:
            self._text = self.body.decode("utf-8", "replace")
        return self._text

    @property
    def cookies(self):
        return [v.split("=", 1)[0].strip() for v in self.h("set-cookie")]


def parse_target(s):
    if "://" not in s:
        s = "https://" + s
    u = urlsplit(s)
    scheme = u.scheme.lower()
    host = u.hostname
    port = u.port or (443 if scheme == "https" else 80)
    default = 443 if scheme == "https" else 80
    hostheader = host if port == default else f"{host}:{port}"
    return Target(scheme, host, port, hostheader), (u.path or "/")


def make_ctx(verify):
    c = ssl.create_default_context()
    if not verify:
        c.check_hostname = False
        c.verify_mode = ssl.CERT_NONE
    return c


async def _read_body(reader, hdrs, timeout):
    te = " ".join(v for k, v in hdrs if k == "transfer-encoding").lower()
    cl = next((v for k, v in hdrs if k == "content-length"), None)
    buf = b""
    try:
        if "chunked" in te:
            while len(buf) < MAX_BODY:
                line = await asyncio.wait_for(reader.readline(), timeout)
                if not line:
                    break
                size = int(line.split(b";")[0].strip() or b"0", 16)
                if size == 0:
                    break
                buf += await asyncio.wait_for(reader.readexactly(size), timeout)
                await asyncio.wait_for(reader.readline(), timeout)
        elif cl is not None and cl.isdigit():
            n = min(int(cl), MAX_BODY)
            try:
                buf = await asyncio.wait_for(reader.readexactly(n), timeout)
            except asyncio.IncompleteReadError as e:
                buf = e.partial
        else:
            while len(buf) < MAX_BODY:
                chunk = await asyncio.wait_for(reader.read(8192), timeout)
                if not chunk:
                    break
                buf += chunk
    except (asyncio.TimeoutError, asyncio.IncompleteReadError, ValueError,
            ConnectionError, ssl.SSLError):
        pass
    enc = " ".join(v for k, v in hdrs if k == "content-encoding").lower()
    if "gzip" in enc and buf:
        try:
            buf = zlib.decompressobj(16 + zlib.MAX_WBITS).decompress(buf)
        except zlib.error:
            pass
    return buf[:MAX_BODY]


async def fetch(t, path, method="GET", headers=None, timeout=8.0, verify=True):
    hdrs = {
        "Host": t.hostheader, "User-Agent": UA,
        "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8",
        "Accept-Language": "en-US,en;q=0.5", "Accept-Encoding": "identity",
        "Connection": "close",
    }
    if headers:
        hdrs.update(headers)
    req = f"{method} {path} HTTP/1.1\r\n" + "".join(f"{k}: {v}\r\n" for k, v in hdrs.items()) + "\r\n"
    r = Resp()
    t0 = time.perf_counter()
    writer = None
    try:
        ctx = make_ctx(verify) if t.scheme == "https" else None
        reader, writer = await asyncio.wait_for(
            asyncio.open_connection(t.host, t.port, ssl=ctx, limit=2 ** 17,
                                    server_hostname=t.host if ctx else None), timeout)
        writer.write(req.encode("latin-1", "replace"))
        await writer.drain()
        head = await asyncio.wait_for(reader.readuntil(b"\r\n\r\n"), timeout)
        lines = head.decode("latin-1").split("\r\n")
        parts = lines[0].split(" ", 2)
        r.status = int(parts[1])
        r.reason = parts[2] if len(parts) > 2 else ""
        for line in lines[1:]:
            if ":" in line:
                k, v = line.split(":", 1)
                r.headers.append((k.strip().lower(), v.strip()))
        if method != "HEAD":
            r.body = await _read_body(reader, r.headers, timeout)
    except asyncio.TimeoutError:
        r.error = "timeout"
    except ConnectionResetError:
        r.error = "reset"
    except asyncio.IncompleteReadError:
        r.error = "closed"
    except ssl.SSLError as e:
        r.error = f"tls:{getattr(e, 'reason', e)}"
    except (OSError, ValueError, IndexError) as e:
        r.error = f"{type(e).__name__}:{e}"
    finally:
        r.elapsed = time.perf_counter() - t0
        if writer is not None:
            try:
                writer.close()
            except Exception:
                pass
    return r


