def similarity(a, b):
    a, b = a[:1500], b[:1500]
    if not a and not b:
        return 1.0
    return difflib.SequenceMatcher(None, a, b).quick_ratio()


def judge(p, c):
    """Compare the payload response (p) with the control response (c). -> (reason, strength) | None"""
    if p.error:
        if c.error:
            return None
        return (f"connection {p.error}", 0.6 if p.error in ("reset", "closed") else 0.3)
    if c.error:
        return None
    if p.status != c.status:
        if p.status in STRONG_CODES:
            return (f"HTTP {p.status} (control {c.status})", 0.85)
        if 300 <= p.status < 400 and BLOCK_WORDS.search(" ".join(p.h("location"))):
            return ("redirect to block/challenge page", 0.7)
        if p.status >= 400 and c.status < 400:
            return (f"HTTP {p.status} (control {c.status})", 0.4)
        return None
    if p.status < 400 and similarity(c.text, p.text) < 0.5 \
            and BLOCK_WORDS.search(p.text) and not BLOCK_WORDS.search(c.text):
        return ("block page served with HTTP 200 (soft block)", 0.6)
    return None


def sig_match_resp(kind, pat, r):
    if kind == "hdr":
        return any(k == pat for k, _ in r.headers)
    if kind == "hdrre":
        return any(re.search(pat, k) for k, _ in r.headers)
    if kind == "hdrv":
        name, rx = pat.split(":", 1)
        return any(k == name and re.search(rx, v, re.I) for k, v in r.headers)
    if kind == "cookie":
        return any(re.search(pat, c, re.I) for c in r.cookies)
    if kind == "body":
        return bool(re.search(pat, r.text, re.I | re.S))
    return False


